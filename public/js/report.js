(async () => {
  const user = await BSG.ui.guard();
  if (!user) return;
  BSG.ui.registerSW();
  const T = BSG.i18n.t;

  const id = new URLSearchParams(location.search).get('id');
  const sheet = document.getElementById('sheet');
  document.getElementById('back').addEventListener('click', (e) => {
    e.preventDefault();
    if (history.length > 1) history.back(); else location.href = id ? `/view.html?id=${id}` : '/history.html';
  });
  document.getElementById('print').addEventListener('click', () => window.print());

  if (!id) { sheet.innerHTML = `<div class="p-4 text-danger">${T('No assessment specified.')}</div>`; return; }

  // enum-aware translate; pass through free text (Arabic/English) unchanged
  const TV = (v) => (v != null && v !== '' ? T(String(v)) : v);
  const esc = BSG.ui.escape;

  // render a field only when it has a value
  function field(label, value) {
    if (value == null || value === '') return '';
    return `<div class="col-md-6 rep-field"><div class="rep-label">${esc(label)}</div><div class="rep-value">${esc(value)}</div></div>`;
  }

  try {
    const { report: a } = await BSG.api.get(`/api/assessments/${id}/report`);
    const media = a.media || [];
    const images = media.filter((m) => m.kind === 'image');
    const videoCount = media.filter((m) => m.kind === 'video').length;
    const gps = (a.latitude != null && a.longitude != null) ? `${a.latitude}, ${a.longitude}` : null;
    const repId = 'BSG-' + String(a.id).padStart(5, '0');
    const dateStr = BSG.ui.fmtDate(a.created_at);

    const buildingRows = [
      field(T('Location'), a.building_location),
      field(T('Building type'), TV(a.building_type)),
      field(T('Floors'), a.num_floors),
      field(T('Year built'), a.year_built),
      field(T('GPS coordinates'), gps),
      field(T('Status'), TV(a.status)),
    ].join('');

    const ownerRows = [
      field(T('Owner name'), a.owner_name),
      field(T('National ID'), a.owner_id_number),
      field(T('Phone'), a.owner_phone),
    ].join('');

    const damageRows = [
      field(T('Damage type'), TV(a.damage_type)),
      field(T('Severity'), TV(a.severity)),
      field(T('Habitability'), TV(a.habitability)),
    ].join('');

    const ownerSection = ownerRows.trim()
      ? `<div class="rep-section">${T('Owner Information')}</div><div class="row">${ownerRows}</div>` : '';
    const notesSection = (a.notes && a.notes.trim())
      ? `<div class="rep-section">${T('Engineer Notes')}</div><p>${esc(a.notes)}</p>` : '';

    const photosSection = images.length
      ? `<div class="rep-section">${T('Photo Documentation')}</div>
         <div class="row g-2 rep-photos">${images.map((m) => `<div class="col-4">${`<img src="/api/media/${m.id}">`}</div>`).join('')}</div>
         ${videoCount ? `<p class="text-muted small mt-2">+ ${videoCount} ${T('video file(s) attached (view in the app).')}</p>` : ''}`
      : '';

    sheet.innerHTML = `
      <div class="sheet-head">
        <div class="d-flex justify-content-between align-items-start flex-wrap">
          <div>
            <div class="h4 fw-bold mb-0">BuildSafe Gaza</div>
            <div>${T('Damage Assessment Report')}</div>
          </div>
          <div class="text-end small">
            <div>${T('Report ID')}: <strong>${repId}</strong></div>
            <div>${T('Generated on')}: ${dateStr}</div>
          </div>
        </div>
      </div>
      <div class="sheet-body">
        <div class="mb-2">${BSG.ui.severityBadge(a.severity)}</div>

        <div class="rep-section">${T('Building Information')}</div>
        <div class="row">${buildingRows}</div>

        ${ownerSection}

        <div class="rep-section">${T('Damage Assessment')}</div>
        <div class="row">${damageRows}</div>

        ${notesSection}

        <div class="rep-section">${T('Assessed By')}</div>
        <div class="row">
          ${field(T('Engineer'), a.engineer ? a.engineer.full_name : null)}
          ${field(T('Email'), a.engineer ? a.engineer.email : null)}
        </div>

        ${photosSection}

        <hr class="my-4">
        <p class="text-center text-muted small mb-0">
          ${T('This is a preliminary field assessment generated by BuildSafe Gaza.')}<br>
          ${T('Islamic University of Gaza — Software Engineering Project')}
        </p>
      </div>`;

    document.title = `${repId} — BuildSafe Gaza`;
  } catch (ex) {
    sheet.innerHTML = `<div class="p-4 text-danger">${T('Could not load assessment:')} ${esc(ex.message)}</div>`;
  }
})();
